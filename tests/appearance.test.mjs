import {projectRoot,hostRoot,hostPath,hostImport} from './helpers/paths.mjs';
import assert from 'node:assert/strict';
const {createJiti}=await hostImport('pi-coding-agent/dist/core/extensions/jiti-loader.js');
const {KeybindingsManager}=await hostImport('pi-coding-agent/dist/core/keybindings.js');
const {CustomEditor,initTheme}=await hostImport('pi-coding-agent/dist/index.js');
const {getEditorTheme,theme}=await hostImport('pi-coding-agent/dist/modes/interactive/theme/theme.js');
const {visibleWidth}=await hostImport('pi-tui/dist/index.js');
const jiti=createJiti(import.meta.url,{alias:{'@earendil-works/pi-coding-agent':hostPath('pi-coding-agent/dist/index.js'),'@earendil-works/pi-tui':hostPath('pi-tui/dist/index.js')}});
const root=projectRoot;initTheme('dark');
const {default:install}=await jiti.import(root+'/src/ui/appearance.ts');
const hooks={};let factory,indicator,message;const previous=()=>{};
const ctx={mode:'tui',ui:{theme,getEditorComponent:()=>previous,setEditorComponent:f=>factory=f,setWorkingIndicator:x=>indicator=x,setWorkingMessage:x=>message=x}};
install({on:(name,fn)=>hooks[name]=fn});hooks.session_start({},ctx);
const editor=factory({requestRender(){},terminal:{rows:40,columns:80}},getEditorTheme(),new KeybindingsManager());
editor.setText('中文 input test');
for(const width of [20,80,120]){
 const lines=editor.render(width);
 assert.ok(lines.every(l=>visibleWidth(l)<=width));assert.ok(lines.some(l=>l.includes('❯')));
 const plain=lines.map(l=>l.replace(/\x1b\[[0-?]*[ -/]*[@-~]/g,''));
 assert.ok(plain[0].startsWith('╭')&&plain[0].endsWith('╮'));
 assert.ok(plain.some(l=>l.startsWith('╰')&&l.endsWith('╯')));
 assert.ok(plain[1].includes('中文'),'no blank row above input');
 assert.equal(editor.borderColor('─'),theme.fg('dim','─'));
}
editor.borderColor=s=>theme.fg('error',s);editor.render(80);
assert.equal(editor.borderColor('─'),theme.fg('dim','─'),'host color assignment must not desynchronize borders');
const plain=s=>s.replace(/\x1b\[[0-?]*[ -/]*[@-~]/g,'');
const label=()=>indicator ? plain(indicator.frames[0]) : undefined;
const delta=type=>hooks.message_update({assistantMessageEvent:{type}},ctx);
hooks.agent_start({},ctx);assert.equal(label(),'Working…');assert.equal(message,'');
delta('thinking_start');assert.equal(label(),'Thinking…');
const thinkingFrames=indicator;delta('thinking_delta');assert.equal(indicator,thinkingFrames,'tokens must not restart animation');
delta('thinking_end');assert.equal(label(),'Working…');
delta('text_delta');assert.equal(label(),'Responding…');
delta('toolcall_start');assert.equal(label(),'Working…');
hooks.tool_execution_start({toolCallId:'a'},ctx);hooks.tool_execution_start({toolCallId:'b'},ctx);
assert.equal(label(),'Running tools…');
hooks.tool_execution_end({toolCallId:'a'},ctx);assert.equal(label(),'Running tools…');
delta('thinking_delta');assert.equal(label(),'Running tools…');
hooks.tool_execution_end({toolCallId:'b'},ctx);assert.equal(label(),'Thinking…');
hooks.message_end({message:{role:'assistant'}},ctx);assert.equal(label(),'Working…');
hooks.agent_end({},ctx);assert.equal(indicator,undefined);
delta('thinking_delta');assert.equal(indicator,undefined,'late events must not restart idle indicator');
